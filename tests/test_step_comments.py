"""Per-step tester comments: stand in for evidence there is nothing to attach."""

import json

import pytest
from conftest import csrf_of

from wstg import ai_review as ar
from wstg import evidence as evmod
from wstg import targets as tm

URL = "/t/www.example.com/wstg/WSTG-IDNT-05"
NOTE = "User names are generated by the system (U + 6 digits); users cannot choose them."


@pytest.fixture
def site(db, cfg):
    tm.create(db, cfg, "example.com", "domain")
    return tm.create(db, cfg, "www.example.com", "fqdn", parent="example.com")


def post(client, url, **data):
    data["csrf"] = csrf_of(client)
    return client.post(url, data=data)


def test_comment_save_show_prompt_and_remove(admin_client, guest_client, db, site):
    assert post(guest_client, URL + "/steps/3/comment", comment=NOTE).status_code == 403
    assert admin_client.post(URL + "/steps/3/comment", data={"comment": NOTE}).status_code in (400, 403)  # no CSRF
    r = post(admin_client, URL + "/steps/3/comment", comment=NOTE + "\r\nSecond line.")
    assert r.status_code == 302 and r.headers["Location"].endswith("#step-3")
    c = tm.step_comments(db, site, "WSTG-IDNT-05")["WSTG-IDNT-05"][3]
    assert c["comment"] == NOTE + "\nSecond line." and c["updated_by"] == "admin"
    page = admin_client.get(URL).get_data(as_text=True)
    assert "Save comment" in page and NOTE in page
    prompt = page[page.index('id="ai-prompt"'):]
    assert "Tester comment (" in prompt and f"     {NOTE}" in prompt and "     Second line." in prompt
    # a comment counts as work started on the test
    idx = admin_client.get("/t/www.example.com/").get_data(as_text=True)
    assert "WSTG-IDNT-05" in idx
    assert tm.status(4, {}, True) == "started"
    # guests see it read-only
    gpage = guest_client.get(URL).get_data(as_text=True)
    assert NOTE in gpage and "Save comment" not in gpage
    # resetting the test keeps it; Remove clears it
    post(admin_client, URL + "/reset")
    assert 3 in tm.step_comments(db, site, "WSTG-IDNT-05")["WSTG-IDNT-05"]
    post(admin_client, URL + "/steps/3/comment", comment=NOTE, clear="1")
    assert tm.step_comments(db, site, "WSTG-IDNT-05") == {}
    assert post(admin_client, URL + "/steps/9/comment", comment="x").status_code == 404


def test_comment_too_long_is_refused(db, site):
    with pytest.raises(tm.TargetError):
        tm.set_step_comment(db, site, "WSTG-IDNT-05", 3, "x" * (tm.MAX_STEP_COMMENT + 1), "admin")


def _answer(steps):
    body = {"test": "WSTG-IDNT-05", "target": "www.example.com", "overall": "pass", "summary": "s",
            "steps": [{"step": n, "verdict": v, "reason": "r"} for n, v in steps]}
    return "```json\n" + json.dumps({"wstg_review": body}) + "\n```"


def test_comment_stands_in_for_manual_evidence_only(cfg, db, site):
    from wstg import catalog as catmod
    cat, store = catmod.load(), evmod.Store(cfg, db)

    def apply(steps):
        rv = ar.parse(_answer(steps), test_id="WSTG-IDNT-05", target_name=site.name, step_count=4)
        return {r["step"]: r for r in ar.apply(db, store, cat, site, rv, "a", "admin", overwrite=True)["results"]}

    res = apply([(3, "pass")])
    assert res[3]["outcome"] == "refused" and "registration-tests" in res[3]["note"]
    tm.set_step_comment(db, site, "WSTG-IDNT-05", 3, NOTE, "admin")
    res = apply([(2, "pass"), (3, "pass"), (4, "pass")])
    assert res[3]["outcome"] == "applied"
    # step 2 reads automatic evidence (auth-pages): a comment never replaces it
    assert res[2]["outcome"] == "refused" and "auth-pages" in res[2]["note"]
    # step 4 also uses registration-tests (covered by the step 3 comment), but enum-tests is still missing
    assert res[4]["outcome"] == "refused" and "enum-tests" in res[4]["note"] and "registration-tests" not in res[4]["note"]
