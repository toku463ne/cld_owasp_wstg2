"""Per-evidence tester comments: a note where there is nothing to attach, with a
`collected` flag that counts the manual evidence as collected without a file."""

import json

import pytest
from conftest import csrf_of

from wstg import ai_review as ar
from wstg import evidence as evmod
from wstg import targets as tm

WSTG = "/t/www.example.com/wstg/WSTG-IDNT-05"
EV = "/t/www.example.com/evidence/registration-tests/comment"
RETURN = "/t/www.example.com/wstg/WSTG-IDNT-05#step-3"
NOTE = "User names are generated by the system (U + 6 digits); users cannot choose them."


@pytest.fixture
def site(db, cfg):
    tm.create(db, cfg, "example.com", "domain")
    return tm.create(db, cfg, "www.example.com", "fqdn", parent="example.com")


def post(client, url, **data):
    data["csrf"] = csrf_of(client)
    return client.post(url, data=data)


def test_comment_save_collected_show_prompt_and_remove(admin_client, guest_client, db, site):
    assert post(guest_client, EV, comment=NOTE).status_code == 403
    assert admin_client.post(EV, data={"comment": NOTE}).status_code in (400, 403)   # no CSRF
    # save, marked collected, returning to the WSTG step it was opened from
    r = post(admin_client, EV, comment=NOTE + "\r\nSecond line.", collected="1", **{"return": RETURN})
    assert r.status_code == 302 and r.headers["Location"].endswith("#step-3")
    c = tm.evidence_comments(db, site, "registration-tests")["registration-tests"]
    assert c["comment"] == NOTE + "\nSecond line." and c["collected"] is True and c["updated_by"] == "admin"

    page = admin_client.get(WSTG).get_data(as_text=True)
    assert "Save comment" in page and NOTE in page and "by tester comment" in page
    prompt = page[page.index('id="ai-prompt"'):]
    assert "Tester comment (" in prompt and f"     {NOTE}" in prompt and "marked collected" in prompt
    # collected by comment counts in the manual tab and the WSTG index evidence count
    assert "by tester comment" in admin_client.get("/t/www.example.com/manual").get_data(as_text=True)
    assert tm.status(4, {}, True) == "started"
    # guests see it read-only
    gpage = guest_client.get(WSTG).get_data(as_text=True)
    assert NOTE in gpage and "Save comment" not in gpage
    # resetting the test keeps it; Remove clears it
    post(admin_client, WSTG + "/reset")
    assert "registration-tests" in tm.evidence_comments(db, site)
    post(admin_client, EV, comment=NOTE, clear="1")
    assert tm.evidence_comments(db, site) == {}


def test_comment_without_collected_does_not_count(admin_client, db, site):
    post(admin_client, EV, comment=NOTE)                       # no collected checkbox
    c = tm.evidence_comments(db, site, "registration-tests")["registration-tests"]
    assert c["collected"] is False
    page = admin_client.get(WSTG).get_data(as_text=True)
    assert NOTE in page and "by tester comment" not in page    # not shown as collected


def test_comment_too_long_is_refused(db, site):
    with pytest.raises(tm.TargetError):
        tm.set_evidence_comment(db, site, "registration-tests", "x" * (tm.MAX_EVIDENCE_COMMENT + 1), True, "admin")


def _answer(steps):
    body = {"test": "WSTG-IDNT-05", "target": "www.example.com", "overall": "pass", "summary": "s",
            "steps": [{"step": n, "verdict": v, "reason": "r"} for n, v in steps]}
    return "```json\n" + json.dumps({"wstg_review": body}) + "\n```"


def test_collected_comment_stands_in_for_manual_evidence_only(cfg, db, site):
    from wstg import catalog as catmod
    cat, store = catmod.load(), evmod.Store(cfg, db)

    def apply(steps):
        rv = ar.parse(_answer(steps), test_id="WSTG-IDNT-05", target_name=site.name, step_count=4)
        return {r["step"]: r for r in ar.apply(db, store, cat, site, rv, "a", "admin", overwrite=True)["results"]}

    res = apply([(3, "pass")])
    assert res[3]["outcome"] == "refused" and "registration-tests" in res[3]["note"]
    # a comment that is not marked collected does not stand in
    tm.set_evidence_comment(db, site, "registration-tests", NOTE, False, "admin")
    assert apply([(3, "pass")])[3]["outcome"] == "refused"
    # marked collected, it stands in for the missing manual evidence
    tm.set_evidence_comment(db, site, "registration-tests", NOTE, True, "admin")
    res = apply([(2, "pass"), (3, "pass"), (4, "pass")])
    assert res[3]["outcome"] == "applied"
    # step 2 reads automatic evidence (auth-pages): a comment never replaces it
    assert res[2]["outcome"] == "refused" and "auth-pages" in res[2]["note"]
    # step 4 also uses registration-tests (covered), but enum-tests is still missing
    assert res[4]["outcome"] == "refused" and "enum-tests" in res[4]["note"] and "registration-tests" not in res[4]["note"]
